// Remix Icon names → font code points, from the remixicon package the web app also uses.
// Run with `pnpm --filter @dibs/mobile icons` after upgrading remixicon.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const css = readFileSync(require.resolve("remixicon/fonts/remixicon.css"), "utf8");
const glyphs = {};
for (const [, name, hex] of css.matchAll(/\.ri-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"/g)) glyphs[name] = parseInt(hex, 16);
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(
  join(here, "..", "components", "ui", "icon-glyphs.ts"),
  `// Generated by scripts/build-icons.mjs from remixicon ${require("remixicon/package.json").version}. Do not edit by hand.\nexport const glyphs = ${JSON.stringify(glyphs)} as const;\nexport type IconName = keyof typeof glyphs;\n`
);
console.log(`${Object.keys(glyphs).length} icons`);
